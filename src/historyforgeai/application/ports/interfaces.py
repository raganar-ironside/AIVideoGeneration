from typing import Protocol
from historyforgeai.domain.models import ShortPlan, Job

class LLMPort(Protocol):
    def create_plan(self, topic: str, context: str, duration: int, scenes: int) -> ShortPlan: ...

class ResearchPort(Protocol):
    def collect(self, topic: str) -> str: ...

class AssetPort(Protocol):
    def fetch(self, query: str, destination: str) -> dict | None: ...

class SpeechPort(Protocol):
    def synthesize(self, text: str, destination: str) -> bool: ...

class RendererPort(Protocol):
    def render(self, plan: ShortPlan, job_dir: str, audio_path: str | None) -> str: ...

class JobRepositoryPort(Protocol):
    def save(self, job: Job) -> None: ...
    def load(self, job_id: str) -> Job: ...
